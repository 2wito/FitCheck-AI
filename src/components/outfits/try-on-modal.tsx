"use client";

import { useRef, useState, useTransition } from "react";
import Image from "next/image";
import Link from "next/link";
import { Check, Download, Heart, Loader2, PersonStanding, RotateCcw, Sparkles, TriangleAlert } from "lucide-react";
import { toast } from "sonner";

import { getBodyPhotoUrl } from "@/actions/profile";
import { generateTryOn, saveTryOn } from "@/actions/try-on";
import { BodyPhotoUpload } from "@/components/profile/body-photo-upload";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog";
import { dataUrlToFile } from "@/lib/image";
import { MAX_TRY_ON_ITEMS } from "@/lib/validations/try-on";

type State =
  | { kind: "loading" }
  | { kind: "needs-photo" }
  | { kind: "generating"; before: string }
  | { kind: "result"; before: string; after: string; saved: boolean }
  | { kind: "error"; before: string | null; message: string };

export function TryOnModal({
  clothingItemIds,
  outfitId,
  compact = false,
}: {
  clothingItemIds: string[];
  // Links saved results to this outfit, when the look has been saved.
  outfitId?: string | null;
  // Icon-only trigger for tight spaces like gallery cards.
  compact?: boolean;
}) {
  const [open, setOpen] = useState(false);
  const [state, setState] = useState<State>({ kind: "loading" });
  const [isSaving, startSaving] = useTransition();
  // Results from a closed or superseded request are ignored.
  const requestId = useRef(0);

  const tooMany = clothingItemIds.length > MAX_TRY_ON_ITEMS;
  const disabled = clothingItemIds.length === 0 || tooMany;
  const disabledReason = tooMany
    ? `Try-on supports up to ${MAX_TRY_ON_ITEMS} items`
    : "Add items to try them on";

  async function start() {
    const id = ++requestId.current;
    setState({ kind: "loading" });
    const result = await getBodyPhotoUrl().catch(() => null);
    if (id !== requestId.current) return;

    if (!result?.success) {
      setState({ kind: "error", before: null, message: result?.error ?? "Something went wrong." });
    } else if (!result.data) {
      setState({ kind: "needs-photo" });
    } else {
      await generate(result.data, id);
    }
  }

  async function generate(before: string, id = ++requestId.current) {
    setState({ kind: "generating", before });
    const result = await generateTryOn({ clothingItemIds }).catch(() => null);
    if (id !== requestId.current) return;

    setState(
      result?.success
        ? { kind: "result", before, after: result.data, saved: false }
        : { kind: "error", before, message: result?.error ?? "Try-on failed. Please try again." },
    );
  }

  function handleOpenChange(nextOpen: boolean) {
    if (isSaving) return;
    setOpen(nextOpen);
    if (nextOpen) {
      void start();
    } else {
      requestId.current++;
    }
  }

  function handleSave() {
    if (state.kind !== "result") return;
    const { after } = state;
    startSaving(async () => {
      const formData = new FormData();
      formData.append("image", await dataUrlToFile(after, `try-on.${extensionOf(after)}`));
      if (outfitId) formData.append("outfitId", outfitId);

      const result = await saveTryOn(formData).catch(() => null);
      if (!result?.success) {
        toast.error(result?.error ?? "Couldn't save the try-on. Please try again.");
        return;
      }
      setState((current) => (current.kind === "result" ? { ...current, saved: true } : current));
      toast.success("Saved to your favorites");
    });
  }

  const trigger = compact ? (
    <Button
      variant="outline"
      size="icon-sm"
      aria-label="Try on me"
      title={disabled ? disabledReason : "Try on me"}
      disabled={disabled}
    />
  ) : (
    <Button variant="outline" title={disabled ? disabledReason : undefined} disabled={disabled} />
  );

  return (
    <Dialog open={open} onOpenChange={handleOpenChange}>
      <DialogTrigger render={trigger}>
        <PersonStanding data-icon={compact ? undefined : "inline-start"} />
        {!compact && "Try on me"}
      </DialogTrigger>
      <DialogContent className="sm:max-w-3xl">
        <DialogHeader>
          <DialogTitle>Virtual try-on</DialogTitle>
          <DialogDescription>See this outfit on you, generated by AI from your photo.</DialogDescription>
        </DialogHeader>

        {state.kind === "loading" && (
          <div className="flex justify-center py-16">
            <Loader2 className="size-6 animate-spin text-muted-foreground" />
          </div>
        )}

        {state.kind === "needs-photo" && (
          <div className="flex flex-col gap-3">
            <p className="text-center text-muted-foreground">
              Add a full-body photo of yourself to try outfits on. You only need to do this once.
            </p>
            <BodyPhotoUpload
              initialUrl={null}
              onChange={(url) => url && generate(url)}
              className="mx-auto w-full max-w-md"
            />
          </div>
        )}

        {(state.kind === "generating" || state.kind === "result") && (
          <div className="grid grid-cols-2 gap-3 sm:gap-4">
            <Photo label="Before" src={state.before} />
            {state.kind === "generating" ? (
              <GeneratingPlaceholder />
            ) : (
              <Photo label="After" src={state.after} />
            )}
          </div>
        )}

        {state.kind === "error" && (
          <div className="flex flex-col items-center gap-3 py-8 text-center">
            <TriangleAlert className="size-6 text-amber-600 dark:text-amber-400" />
            <p className="max-w-md">{state.message}</p>
            {state.before && (
              <Button variant="outline" onClick={() => generate(state.before!)}>
                <RotateCcw data-icon="inline-start" />
                Try again
              </Button>
            )}
          </div>
        )}

        {state.kind === "result" && (
          <>
            <p className="text-center text-xs text-muted-foreground">
              AI-generated preview. Real fit, colors and proportions may differ.
            </p>
            <DialogFooter>
              <Button variant="outline" onClick={() => generate(state.before)} disabled={isSaving}>
                <RotateCcw data-icon="inline-start" />
                Regenerate
              </Button>
              <Button
                variant="outline"
                nativeButton={false}
                render={<a href={state.after} download={`fitcheck-try-on.${extensionOf(state.after)}`} />}
              >
                <Download data-icon="inline-start" />
                Download
              </Button>
              {state.saved ? (
                <Button variant="secondary" nativeButton={false} render={<Link href="/profile" />}>
                  <Check data-icon="inline-start" />
                  Saved · View favorites
                </Button>
              ) : (
                <Button onClick={handleSave} disabled={isSaving}>
                  {isSaving ? (
                    <Loader2 data-icon="inline-start" className="animate-spin" />
                  ) : (
                    <Heart data-icon="inline-start" />
                  )}
                  Save to favorites
                </Button>
              )}
            </DialogFooter>
          </>
        )}
      </DialogContent>
    </Dialog>
  );
}

// "data:image/png;base64,..." -> "png"
function extensionOf(dataUrl: string) {
  const mediaType = dataUrl.slice(5, dataUrl.indexOf(";"));
  return mediaType === "image/jpeg" ? "jpg" : mediaType.split("/")[1] || "png";
}

function Photo({ label, src }: { label: string; src: string }) {
  return (
    <figure className="flex flex-col gap-1.5">
      <div className="relative aspect-[3/4] overflow-hidden rounded-xl bg-muted">
        {/* Signed and data URLs: nothing for the image optimizer to cache. */}
        <Image src={src} alt={`${label} try-on`} fill unoptimized className="object-contain" />
      </div>
      <figcaption className="text-center text-xs font-medium text-muted-foreground">{label}</figcaption>
    </figure>
  );
}

function GeneratingPlaceholder() {
  return (
    <figure className="flex flex-col gap-1.5" aria-live="polite">
      <div className="relative flex aspect-[3/4] flex-col items-center justify-center gap-3 overflow-hidden rounded-xl bg-muted p-4 text-center">
        <div className="absolute inset-0 animate-pulse bg-gradient-to-b from-muted via-foreground/5 to-muted" />
        <Sparkles className="relative size-6 animate-bounce" />
        <p className="relative text-sm font-medium">Fitting outfit onto your photo...</p>
        <p className="relative text-xs text-muted-foreground">This usually takes 10–30 seconds.</p>
      </div>
      <figcaption className="text-center text-xs font-medium text-muted-foreground">After</figcaption>
    </figure>
  );
}
